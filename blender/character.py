"""
Stylized character: sleepy guy in an oversized grey hoodie, black skinny
jeans, white sneakers and AirPods. Built from smooth primitives + metaball
hair so it can be generated by script.

    build_character(parent, pose="sit" | "stand")

Coordinates below are three.js style (Y up, character faces +Z, origin on
the floor under the pelvis). P() converts to Blender's Z-up.
"""

import math

import bpy
from mathutils import Vector

# A metaball's visible surface sits at ~0.575 x its "radius" setting.
MB_SURFACE = 0.575


def P(x, y, z):
    return Vector((x, -z, y))


def _hex(h):
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    return tuple(((v + 0.055) / 1.055) ** 2.4 if v > 0.04045 else v / 12.92 for v in c)


_M = {}


def mat(name, color, rough=0.8):
    key = "Char_" + name
    if key in _M:
        return _M[key]
    m = bpy.data.materials.new(key)
    try:
        m.use_nodes = True
    except Exception:
        pass
    b = m.node_tree.nodes["Principled BSDF"]
    b.inputs["Base Color"].default_value = (*_hex(color), 1)
    b.inputs["Roughness"].default_value = rough
    m.diffuse_color = (*_hex(color), 1)  # viewport / workbench colour
    _M[key] = m
    return m


def _active():
    return bpy.context.active_object


def _finish(o, name, m, parent):
    o.name = name
    o.data.materials.append(m)
    bpy.ops.object.shade_smooth()
    if parent:
        o.parent = parent
    return o


def ellipsoid(name, c, radii, m, parent):
    bpy.ops.mesh.primitive_uv_sphere_add(radius=1, segments=32, ring_count=16)
    o = _active()
    o.location = P(*c)
    o.scale = (radii[0], radii[2], radii[1])  # three (x,y,z) radii -> blender (x,z,y)
    return _finish(o, name, m, parent)


def capsule(name, a, b, r, m, parent, r2=None):
    """Smooth limb from point a to b (tapers to r2 if given)."""
    A, B = P(*a), P(*b)
    d = B - A
    bpy.ops.mesh.primitive_cone_add(radius1=r, radius2=r2 or r, depth=d.length, vertices=24)
    o = _active()
    o.location = (A + B) / 2
    o.rotation_mode = "QUATERNION"
    o.rotation_quaternion = d.to_track_quat("Z", "Y")
    bpy.ops.object.shade_smooth()
    o.name = name
    o.data.materials.append(m)
    parts = [o]
    for p, rr in ((A, r), (B, r2 or r)):
        bpy.ops.mesh.primitive_uv_sphere_add(radius=rr, segments=24, ring_count=12, location=p)
        bpy.ops.object.shade_smooth()
        s = _active()
        s.data.materials.append(m)
        parts.append(s)
    bpy.ops.object.select_all(action="DESELECT")
    for p in parts:
        p.select_set(True)
    bpy.context.view_layer.objects.active = o
    bpy.ops.object.join()
    if parent:
        o.parent = parent
    return o


def rounded_box(name, c, size, radius, m, parent, rx=0.0):
    bpy.ops.mesh.primitive_cube_add(size=1)
    o = _active()
    o.location = P(*c)
    o.scale = (size[0], size[2], size[1])
    o.rotation_euler = (rx, 0, 0)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    bev = o.modifiers.new("Round", "BEVEL")
    bev.width = radius
    bev.segments = 5
    bev.limit_method = "NONE"
    sub = o.modifiers.new("Smooth", "SUBSURF")
    sub.levels = 1
    sub.render_levels = 1
    return _finish(o, name, m, parent)


def torus(name, c, major, minor, m, parent, rx=0.0):
    bpy.ops.mesh.primitive_torus_add(major_radius=major, minor_radius=minor,
                                     major_segments=32, minor_segments=12)
    o = _active()
    o.location = P(*c)
    o.rotation_euler = (rx, 0, 0)
    return _finish(o, name, m, parent)


def hair(name, head, m, parent):
    """Floppy mop-top made of metaballs (which melt together), converted to a mesh."""
    hx, hy, hz = head
    mb = bpy.data.metaballs.new(name)
    mb.resolution = 0.006
    mb.render_resolution = 0.006
    mb.threshold = 0.6
    ob = bpy.data.objects.new(name, mb)
    bpy.context.collection.objects.link(ob)

    def blob(c, radii):
        """Ellipsoid whose visible surface has these radii (three.js axes)."""
        r = max(radii) / MB_SURFACE
        e = mb.elements.new()
        e.type = "ELLIPSOID"
        e.co = P(hx + c[0], hy + c[1], hz + c[2])
        e.radius = r
        big = max(radii)
        e.size_x, e.size_y, e.size_z = radii[0] / big, radii[2] / big, radii[1] / big

    def strand(a, b, thickness):
        A = P(hx + a[0], hy + a[1], hz + a[2])
        B = P(hx + b[0], hy + b[1], hz + b[2])
        d = B - A
        e = mb.elements.new()
        e.type = "CAPSULE"
        e.co = (A + B) / 2
        e.radius = thickness / MB_SURFACE
        e.size_x = d.length / 2
        e.rotation = d.to_track_quat("X", "Z")

    # skull cap + back of head + nape
    blob((0, 0.045, -0.012), (0.142, 0.125, 0.15))
    blob((0, -0.02, -0.045), (0.138, 0.125, 0.12))
    blob((0, -0.095, -0.07), (0.105, 0.05, 0.07))
    # sides over the temples, down to the top of the ears
    for s in (-1, 1):
        strand((s * 0.115, 0.07, 0.035), (s * 0.135, 0.0, 0.045), 0.026)
        strand((s * 0.115, 0.06, -0.05), (s * 0.135, -0.04, -0.045), 0.03)
    # heavy fringe: centre-parted strands curving out over the brows
    for x0, x1, y1 in [(-0.08, -0.11, 0.05), (-0.052, -0.075, 0.035), (-0.024, -0.036, 0.04),
                       (0.024, 0.036, 0.04), (0.052, 0.077, 0.035), (0.08, 0.112, 0.05)]:
        strand((x0, 0.13, 0.05), (x1, y1, 0.138), 0.028)

    bpy.ops.object.select_all(action="DESELECT")
    ob.select_set(True)
    bpy.context.view_layer.objects.active = ob
    bpy.ops.object.convert(target="MESH")
    o = _active()
    o.name = name
    o.data.materials.append(m)
    bpy.ops.object.shade_smooth()
    if parent:
        o.parent = parent
    return o


def build_character(parent=None, pose="sit", name="Character"):
    SKIN = mat("Skin", "#f6d2bd", 0.55)
    BLUSH = mat("Blush", "#ee8f95", 0.6)
    EYEBAG = mat("EyeBag", "#dba3a3", 0.6)
    HAIR = mat("Hair", "#0d0d0f", 0.45)
    HOODIE = mat("Hoodie", "#8c8783", 1.0)
    HOODIE_DARK = mat("HoodieRib", "#7f7a76", 1.0)
    PANTS = mat("Pants", "#141416", 0.7)
    SHOE = mat("Shoe", "#f4f4f2", 0.5)
    SOLE = mat("Sole", "#e2e0dc", 0.6)
    WHITE = mat("AirPods", "#fbfbfb", 0.25)
    EYE = mat("EyeWhite", "#f6f2ee", 0.3)
    PUPIL = mat("Pupil", "#1a1210", 0.2)
    LIP = mat("Mouth", "#a56060", 0.6)

    root = bpy.data.objects.new(name, None)
    bpy.context.collection.objects.link(root)
    if parent:
        root.parent = parent

    sit = pose in ("sit", "type", "sleep")
    H = 0.56 if sit else 0.86  # pelvis height
    cfg = POSES.get(pose, POSES["sit"])

    def leaned(p):
        """Where an upright upper-body point ends up after leaning forward around the pelvis."""
        a = cfg["lean"]
        x, y, z = p
        dy = y - H
        return (x, H + dy * math.cos(a) - z * math.sin(a), dy * math.sin(a) + z * math.cos(a))

    def make_arm(s, sh, elbow, wrist, parent):
        capsule(f"UpperSleeve{s}", sh, elbow, 0.07, HOODIE, parent, r2=0.065)
        capsule(f"LowerSleeve{s}", elbow, wrist, 0.065, HOODIE, parent, r2=0.056)
        cuff_end = tuple(w + (w - e) * 0.16 for w, e in zip(wrist, elbow))
        capsule(f"Cuff{s}", wrist, cuff_end, 0.045, HOODIE_DARK, parent)
        hand = tuple(w + (w - e) * 0.42 for w, e in zip(wrist, elbow))
        capsule(f"Hand{s}", cuff_end, hand, 0.032, SKIN, parent, r2=0.028)

    # ---------- legs (black skinny jeans + chunky white sneakers)
    for s in (-1, 1):
        hip = (s * 0.08, H, 0.0)
        if sit:
            knee = (s * 0.1, H + 0.02, 0.42)
            ankle = (s * 0.105, 0.12, 0.45)
        else:
            knee = (s * 0.08, 0.47, 0.01)
            ankle = (s * 0.08, 0.12, 0.0)
        capsule(f"Thigh{s}", hip, knee, 0.062, PANTS, root, r2=0.052)
        capsule(f"Shin{s}", knee, ankle, 0.05, PANTS, root, r2=0.042)
        ax, _, az = ankle
        rounded_box(f"Shoe{s}", (ax, 0.07, az + 0.06), (0.12, 0.11, 0.3), 0.05, SHOE, root)
        rounded_box(f"Sole{s}", (ax, 0.02, az + 0.06), (0.13, 0.04, 0.315), 0.016, SOLE, root)

    # ---------- oversized hoodie
    T = H + 0.3  # torso centre
    rounded_box("HoodieBody", (0, T, -0.01), (0.45, 0.58, 0.28), 0.13, HOODIE, root)
    rounded_box("HoodieHem", (0, H + 0.03, -0.01), (0.43, 0.07, 0.26), 0.03, HOODIE_DARK, root)
    rounded_box("HoodiePocket", (0, H + 0.16, 0.125), (0.27, 0.13, 0.03), 0.014, HOODIE_DARK, root)
    rounded_box("Hood", (0, H + 0.58, -0.11), (0.28, 0.18, 0.14), 0.07, HOODIE, root, rx=0.3)
    torus("HoodCollar", (0, H + 0.59, -0.005), 0.075, 0.03, HOODIE, root)

    # sleeves for the upright poses (they ride along with the UpperBody pivot)
    if pose in ("sit", "stand"):
        for s in (-1, 1):
            sh = (s * 0.215, H + 0.49, -0.01)
            if sit:
                elbow = (s * 0.25, H + 0.24, 0.1)
                wrist = (s * 0.17, H + 0.12, 0.32)
            else:
                elbow = (s * 0.245, H + 0.21, -0.01)
                wrist = (s * 0.255, H - 0.05, 0.02)
            make_arm(s, sh, elbow, wrist, root)

    # ---------- neck + head (big, stylised)
    capsule("Neck", (0, H + 0.55, 0.0), (0, H + 0.67, 0.0), 0.05, SKIN, root)
    hy = H + 0.775
    head = (0, hy, 0.0)
    ellipsoid("Head", head, (0.13, 0.155, 0.135), SKIN, root)

    for s in (-1, 1):
        ellipsoid(f"Ear{s}", (s * 0.128, hy - 0.01, -0.005), (0.018, 0.04, 0.028), SKIN, root)
        ellipsoid(f"AirPod{s}", (s * 0.142, hy - 0.015, 0.012), (0.014, 0.014, 0.014), WHITE, root)
        capsule(f"AirPodStem{s}", (s * 0.143, hy - 0.022, 0.016), (s * 0.143, hy - 0.06, 0.02), 0.006, WHITE, root)
        # sleepy half-closed eyes
        ex = s * 0.05
        ellipsoid(f"EyeWhite{s}", (ex, hy, 0.118), (0.024, 0.016, 0.012), EYE, root)
        ellipsoid(f"Pupil{s}", (ex, hy - 0.003, 0.128), (0.011, 0.011, 0.006), PUPIL, root)
        ellipsoid(f"Eyelid{s}", (ex, hy + 0.009, 0.12), (0.027, 0.014, 0.015), SKIN, root)
        ellipsoid(f"EyeBag{s}", (ex, hy - 0.017, 0.124), (0.02, 0.007, 0.006), EYEBAG, root)
        ellipsoid(f"Blush{s}", (s * 0.08, hy - 0.04, 0.097), (0.027, 0.02, 0.008), BLUSH, root)

    ellipsoid("Nose", (0, hy - 0.025, 0.136), (0.012, 0.016, 0.012), SKIN, root)
    ellipsoid("Mouth", (0, hy - 0.075, 0.116), (0.017, 0.0035, 0.005), LIP, root)

    hair("Hair", head, HAIR, root)

    # ---------- pivots, so the website can animate parts without a skeleton
    # Character
    #  ├─ legs + shoes (static)
    #  └─ UpperBody  (pivot at the pelvis: breathing / leaning)
    #      └─ HeadPivot  (pivot at the top of the neck: nodding / tilting)
    neck_top = H + 0.67
    upper = bpy.data.objects.new("UpperBody", None)
    bpy.context.collection.objects.link(upper)
    upper.parent = root
    upper.location = P(0, H, 0)
    head_pivot = bpy.data.objects.new("HeadPivot", None)
    bpy.context.collection.objects.link(head_pivot)
    head_pivot.parent = upper
    head_pivot.location = P(0, neck_top - H, 0)

    head_parts = ("Head", "Ear", "AirPod", "EyeWhite", "Pupil", "Eyelid", "EyeBag",
                  "Blush", "Nose", "Mouth", "Hair")
    upper_parts = ("Hoodie", "Hood", "UpperSleeve", "LowerSleeve", "Cuff", "Hand", "Neck")
    for o in list(root.children):
        if o.name.startswith(head_parts):
            o.parent = head_pivot
            o.location = o.location - P(0, neck_top, 0)
        elif o.name.startswith(upper_parts):
            o.parent = upper
            o.location = o.location - P(0, H, 0)

    # ---------- pose: lean the upper body, turn the head
    upper.rotation_euler = (cfg["lean"], 0, 0)
    pitch, roll, yaw = cfg["head"]
    head_pivot.rotation_euler = (pitch, -roll, yaw)  # three.js (x, z, y) -> blender (x, -y, z)

    # posed arms are placed in the final pose directly (they stay still while
    # the body breathes, so hands stay planted on the desk)
    if "arms" in cfg:
        for s in (-1, 1):
            sh = leaned((s * 0.215, H + 0.49, -0.01))
            elbow, wrist = cfg["arms"](s)
            make_arm(s, sh, elbow, wrist, root)

    if cfg.get("eyes_closed"):
        for o in head_pivot.children:
            if o.name.startswith("Eyelid"):
                o.location.z -= 0.009  # blender z = three.js y
                o.scale.z *= 1.35
    return root


# Poses. Arm points are in character space (three.js axes, facing +Z); the
# desk top is at y=0.775 and starts 0.25 in front of the pelvis.
POSES = {
    "stand": {"lean": 0.0, "head": (0.0, 0.0, 0.0)},
    "sit": {"lean": 0.0, "head": (0.0, 0.0, 0.0)},
    "type": {
        "lean": 0.15,
        "head": (0.15, 0.0, 0.0),  # looking down at the monitor
        "arms": lambda s: ((s * 0.25, 0.82, 0.2), (s * 0.11, 0.81, 0.48)),
    },
    "sleep": {
        "lean": 0.8,
        "head": (0.6, 0.5, 0.2),  # face down, cheek on the arms
        "eyes_closed": True,
        # folded arms on the desk, forearms crossing under the head
        "arms": lambda s: ((s * 0.32, 0.84, 0.58), (-s * 0.06, 0.84, 0.64 if s < 0 else 0.7)),
    },
}
